COMMENT ON TABLE APP_PASSWORD_HISTORY
IS
'Historical password hashes and salts used to prevent password reuse.';


COMMENT ON COLUMN APP_PASSWORD_HISTORY.HISTORY_ID
IS
'Primary identifier for a password history record.';


COMMENT ON COLUMN APP_PASSWORD_HISTORY.USER_ID
IS
'Application user associated with the historical password.';


COMMENT ON COLUMN APP_PASSWORD_HISTORY.PASSWORD_HASH
IS
'SHA-256 password hash generated by PKG_SECURITY_HASH.';


COMMENT ON COLUMN APP_PASSWORD_HISTORY.PASSWORD_SALT
IS
'Random password salt associated with PASSWORD_HASH.';


COMMENT ON COLUMN APP_PASSWORD_HISTORY.CHANGED_AT
IS
'Timestamp when the password was stored in password history.';


