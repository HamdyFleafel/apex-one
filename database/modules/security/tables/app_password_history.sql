SET DEFINE OFF
SET SERVEROUTPUT ON
SET VERIFY OFF
SET FEEDBACK ON
SET SQLBLANKLINES ON


DECLARE
    l_exists NUMBER;
BEGIN

    SELECT COUNT(*)
      INTO l_exists
      FROM USER_TABLES
     WHERE TABLE_NAME = 'APP_PASSWORD_HISTORY';


    IF l_exists = 0 THEN

        EXECUTE IMMEDIATE q'[
            CREATE TABLE APP_PASSWORD_HISTORY
            (
                HISTORY_ID
                    NUMBER
                    GENERATED BY DEFAULT AS IDENTITY
                    NOT NULL,

                USER_ID
                    NUMBER(19)
                    NOT NULL,

                PASSWORD_HASH
                    VARCHAR2(2000 CHAR)
                    NOT NULL,

                PASSWORD_SALT
                    VARCHAR2(512 CHAR)
                    NOT NULL,

                CHANGED_AT
                    TIMESTAMP WITH LOCAL TIME ZONE
                    DEFAULT SYSTIMESTAMP
                    NOT NULL,

                CONSTRAINT PK_APP_PASSWORD_HISTORY
                    PRIMARY KEY (HISTORY_ID),

                CONSTRAINT FK_APP_PASSWORD_HISTORY_USER
                    FOREIGN KEY (USER_ID)
                    REFERENCES APP_USERS (USER_ID)
            )
            TABLESPACE APEXONE_DATA
        ]';


        DBMS_OUTPUT.PUT_LINE(
            'APP_PASSWORD_HISTORY created.'
        );


    ELSE

        DBMS_OUTPUT.PUT_LINE(
            'APP_PASSWORD_HISTORY already exists.'
        );

    END IF;

END;
/


PROMPT
PROMPT ============================================================================
PROMPT Creating APP_PASSWORD_HISTORY lookup index
PROMPT ============================================================================
PROMPT


DECLARE
    l_exists NUMBER;
BEGIN

    SELECT COUNT(*)
      INTO l_exists
      FROM USER_INDEXES
     WHERE INDEX_NAME = 'IX_APP_PASSWORD_HISTORY_USER';


    IF l_exists = 0 THEN

        EXECUTE IMMEDIATE q'[
            CREATE INDEX IX_APP_PASSWORD_HISTORY_USER
            ON APP_PASSWORD_HISTORY
            (
                USER_ID,
                CHANGED_AT DESC
            )
            TABLESPACE APEXONE_INDEX
        ]';


        DBMS_OUTPUT.PUT_LINE(
            'IX_APP_PASSWORD_HISTORY_USER created.'
        );


    ELSE

        DBMS_OUTPUT.PUT_LINE(
            'IX_APP_PASSWORD_HISTORY_USER already exists.'
        );

    END IF;

END;
/


